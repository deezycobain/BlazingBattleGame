import fs from 'node:fs/promises';
import path from 'node:path';
const ROOT=process.cwd();
const file=path.join(ROOT,'dist','index.html');
const html=await fs.readFile(file,'utf8');
const needle="else if(f.kind==='senkuBombProjectile')";
const i=html.indexOf(needle);
if(i<0) throw new Error('Senku bomb projectile renderer not found');
const snippet=html.slice(i,Math.min(html.length,i+5000));
await fs.mkdir(path.join(ROOT,'dist','_debug'),{recursive:true});
await fs.writeFile(path.join(ROOT,'dist','_debug','bomb-render.txt'),snippet);
console.log('Bomb renderer inspection artifact written');